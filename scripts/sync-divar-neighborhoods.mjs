#!/usr/bin/env node
/**
 * Refresh the Isfahan neighborhood catalog from Divar before building.
 * Fetches only the city/district metadata endpoint; no listing or personal data.
 * Failure is non-fatal: the last committed generated catalog remains available.
 */
import { writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(scriptDir, "../src/lib/divar-neighborhoods-isfahan.generated.ts");
const endpoint = "https://api.divar.ir/v8/places/cities/3/districts";

const header = "/**\n * Generated by scripts/sync-divar-neighborhoods.mjs.\n * City catalog: Isfahan (Divar city id 3).\n * Do not edit this file manually; the build-time sync keeps it current.\n */\nexport type DivarBbox = [number, number, number, number];\n\nexport type DivarDistrictRecord = {\n  id: number | null;\n  name: string;\n  slug: string;\n  second_slug?: string;\n  default_location?: { latitude: number; longitude: number } | null;\n  centroid?: { latitude: number; longitude: number } | null;\n  bbox?: DivarBbox | null;\n  radius?: number;\n  neighbors?: Array<number | string>;\n  tags?: Array<{ title: string; type: string; display_text?: string }>;\n  polygon_encoded?: string;\n  multi_polygon_encoded?: string[];\n  multi_polygon?: unknown[];\n};\n\nexport type DivarIsfahanCatalog = {\n  cityId: number;\n  source: \"Divar\" | \"OpenStreetMap fallback\";\n  syncedAt: string | null;\n  districts: DivarDistrictRecord[];\n};\n\n";

function finite(value) {
  const result = Number(value);
  return Number.isFinite(result) ? result : null;
}

function validPoint(point) {
  if (!point || typeof point !== "object") return null;
  const latitude = finite(point.latitude);
  const longitude = finite(point.longitude);
  if (latitude == null || longitude == null) return null;
  if (latitude < 30 || latitude > 35 || longitude < 49 || longitude > 54) return null;
  return { latitude, longitude };
}

function validBbox(value) {
  if (!Array.isArray(value) || value.length !== 4) return null;
  const box = value.map(finite);
  if (box.some((part) => part == null)) return null;
  const [west, south, east, north] = box;
  if (west < 49 || east > 54 || south < 30 || north > 35) return null;
  if (west >= east || south >= north) return null;
  return box;
}

function normalizeDistrict(row) {
  if (!row || typeof row !== "object" || !String(row.name ?? "").trim()) return null;
  const point = validPoint(row.default_location) ?? validPoint(row.centroid);
  const bbox = validBbox(row.bbox);
  const numericId = finite(row.id);
  const tags = Array.isArray(row.tags)
    ? row.tags.filter((tag) => tag && typeof tag.title === "string")
        .slice(0, 30)
        .map((tag) => ({
          title: String(tag.title),
          type: String(tag.type ?? ""),
          ...(tag.display_text ? { display_text: String(tag.display_text) } : {}),
        }))
    : [];
  return {
    id: numericId == null ? null : numericId,
    name: String(row.name).trim(),
    slug: String(row.slug ?? ""),
    second_slug: String(row.second_slug ?? ""),
    default_location: point,
    centroid: validPoint(row.centroid),
    bbox,
    radius: finite(row.radius) ?? 0,
    neighbors: Array.isArray(row.neighbors) ? row.neighbors.slice(0, 100) : [],
    tags,
    polygon_encoded: String(row.polygon_encoded ?? ""),
    multi_polygon_encoded: Array.isArray(row.multi_polygon_encoded)
      ? row.multi_polygon_encoded.filter((value) => typeof value === "string")
      : [],
    multi_polygon: Array.isArray(row.multi_polygon) ? row.multi_polygon : [],
  };
}

async function main() {
  try {
    const response = await fetch(endpoint, {
      headers: {
        accept: "application/json",
        "user-agent": "HirmandRealEstate-NeighborhoodSync/1.0 (+https://hirmandrealestate.ir)",
      },
      signal: AbortSignal.timeout(18000),
    });
    if (!response.ok) throw new Error("Divar endpoint responded with HTTP " + response.status);
    const payload = await response.json();
    const rows = Array.isArray(payload) ? payload : payload?.districts;
    if (!Array.isArray(rows) || rows.length < 25) {
      throw new Error("Divar returned an empty or incomplete Isfahan neighborhood catalog");
    }
    const districts = rows.map(normalizeDistrict).filter(Boolean);
    const coordinateCount = districts.filter((district) => district.default_location || district.bbox).length;
    if (districts.length < 25 || coordinateCount < 20) {
      throw new Error("Divar catalog did not contain enough usable neighborhood locations");
    }

    const catalog = {
      cityId: 3,
      source: "Divar",
      syncedAt: new Date().toISOString(),
      districts,
    };
    await writeFile(
      target,
      header + "export const DIVAR_ISFAHAN_CATALOG: DivarIsfahanCatalog = " +
        JSON.stringify(catalog, null, 2) + ";\n",
      "utf8",
    );
    process.stdout.write(
      "[divar-neighborhood-sync] Synced " + districts.length +
      " Isfahan districts (" + coordinateCount + " with map geometry/points).\n",
    );
  } catch (error) {
    let cached = false;
    try {
      const current = await readFile(target, "utf8");
      cached = current.includes('"source": "Divar"') &&
        (current.match(/"name":/g) ?? []).length > 25;
    } catch {
      // A first build may have only the checked-in fallback catalog.
    }
    process.stderr.write(
      "[divar-neighborhood-sync] Could not refresh the catalog: " +
      String(error?.message ?? error) + ". " +
      (cached ? "Using the last cached Divar catalog.\n" : "Using the checked-in fallback locations.\n"),
    );
  }
}

await main();
