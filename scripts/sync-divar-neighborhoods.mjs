#!/usr/bin/env node
/**
 * Refresh the Isfahan neighborhood catalog from Divar before building.
 * Fetches only the city/district metadata endpoint; no listing or personal data.
 * Failure is non-fatal: the last committed generated catalog remains available.
 */
import { writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(scriptDir, "../src/lib/divar-neighborhoods-isfahan.generated.ts");
const citiesEndpoint = "https://api.divar.ir/v8/places/cities";

const header = "/**\n * Generated by scripts/sync-divar-neighborhoods.mjs.\n * City catalog: Isfahan, discovered dynamically from Divar's city list.\n * Do not edit this file manually; the build-time sync keeps it current.\n */\nexport type DivarBbox = [number, number, number, number];\n\nexport type DivarDistrictRecord = {\n  id: number | null;\n  name: string;\n  slug: string;\n  second_slug?: string;\n  default_location?: { latitude: number; longitude: number } | null;\n  centroid?: { latitude: number; longitude: number } | null;\n  bbox?: DivarBbox | null;\n  radius?: number;\n  neighbors?: Array<number | string>;\n  tags?: Array<{ title: string; type: string; display_text?: string }>;\n  polygon_encoded?: string;\n  multi_polygon_encoded?: string[];\n  multi_polygon?: unknown[];\n};\n\nexport type DivarIsfahanCatalog = {\n  cityId: number;\n  source: \"Divar\" | \"OpenStreetMap fallback\";\n  syncedAt: string | null;\n  districts: DivarDistrictRecord[];\n};\n\n";

function finite(value) {
  const result = Number(value);
  return Number.isFinite(result) ? result : null;
}

function validPoint(point) {
  if (!point || typeof point !== "object") return null;
  const latitude = finite(point.latitude ?? point.lat ?? point.lat_e7 ?? point.latE7);
  const longitude = finite(point.longitude ?? point.lng ?? point.lon ?? point.long ?? point.lng_e7 ?? point.lngE7);
  if (latitude == null || longitude == null) return null;
  // Some protobuf endpoints encode coordinates in E7 integers.
  const normalizedLatitude = Math.abs(latitude) > 1000 ? latitude / 1e7 : latitude;
  const normalizedLongitude = Math.abs(longitude) > 1000 ? longitude / 1e7 : longitude;
  if (normalizedLatitude < 30 || normalizedLatitude > 35 || normalizedLongitude < 49 || normalizedLongitude > 54) return null;
  return { latitude: normalizedLatitude, longitude: normalizedLongitude };
}

function validBbox(value) {
  let raw = value;
  if (!Array.isArray(raw) && raw && typeof raw === "object") {
    const west = raw.west ?? raw.minLongitude ?? raw.min_longitude ?? raw.min_lng;
    const south = raw.south ?? raw.minLatitude ?? raw.min_latitude ?? raw.min_lat;
    const east = raw.east ?? raw.maxLongitude ?? raw.max_longitude ?? raw.max_lng;
    const north = raw.north ?? raw.maxLatitude ?? raw.max_latitude ?? raw.max_lat;
    if ([west, south, east, north].every((part) => part != null)) raw = [west, south, east, north];
  }
  if (!Array.isArray(raw) || raw.length !== 4) return null;
  let box = raw.map(finite);
  if (box.some((part) => part == null)) return null;
  if (box.some((part) => Math.abs(part) > 1000)) box = box.map((part) => part / 1e7);
  const [west, south, east, north] = box;
  if (west < 49 || east > 54 || south < 30 || north > 35) return null;
  if (west >= east || south >= north) return null;
  return box;
}

function normalizeDistrict(row) {
  if (!row || typeof row !== "object" || !String(row.name ?? "").trim()) return null;
  const point = validPoint(row.default_location ?? row.defaultLocation ?? row.center ?? row.location) ?? validPoint(row.centroid ?? row.center_point);
  const bbox = validBbox(row.bbox);
  const numericId = finite(row.id);
  const tags = Array.isArray(row.tags)
    ? row.tags.filter((tag) => tag && typeof tag.title === "string")
        .slice(0, 30)
        .map((tag) => ({
          title: String(tag.title),
          type: String(tag.type ?? ""),
          ...(tag.display_text ? { display_text: String(tag.display_text) } : {}),
        }))
    : [];
  return {
    id: numericId == null ? null : numericId,
    name: String(row.name).trim(),
    slug: String(row.slug ?? ""),
    second_slug: String(row.second_slug ?? ""),
    default_location: point,
    centroid: validPoint(row.centroid),
    bbox,
    radius: finite(row.radius) ?? 0,
    neighbors: Array.isArray(row.neighbors) ? row.neighbors.slice(0, 100) : [],
    tags,
    polygon_encoded: String(row.polygon_encoded ?? ""),
    multi_polygon_encoded: Array.isArray(row.multi_polygon_encoded)
      ? row.multi_polygon_encoded.filter((value) => typeof value === "string")
      : [],
    multi_polygon: Array.isArray(row.multi_polygon) ? row.multi_polygon : [],
  };
}

async function fetchJson(url, timeout = 18000) {
  const response = await fetch(url, {
    headers: {
      accept: "application/json",
      "user-agent": "HirmandRealEstate-NeighborhoodSync/1.0 (+https://hirmandrealestate.ir)",
    },
    signal: AbortSignal.timeout(timeout),
  });
  if (!response.ok) throw new Error("Divar endpoint responded with HTTP " + response.status + " (" + url + ")");
  return response.json();
}

function listRows(payload, keys) {
  if (Array.isArray(payload)) return payload;
  for (const key of keys) if (Array.isArray(payload?.[key])) return payload[key];
  return [];
}

function resolveIsfahanCityId(row) {
  const textValues = [
    row?.name, row?.display, row?.title, row?.slug, row?.city_name,
    row?.cityName, row?.name_fa, row?.persian_name, row?.label,
  ].filter((value) => value != null).map(String);
  const matches = textValues.some((value) => /اصفهان|isfahan|esfahan/i.test(value));
  if (!matches) return null;
  return finite(row?.id ?? row?.city_id ?? row?.cityId ?? row?.value);
}

async function main() {
  try {
    const cityPayload = await fetchJson(citiesEndpoint, 12000);
    const cityRows = listRows(cityPayload, ["cities", "places", "city_list", "items"]);
    const isfahan = cityRows.find((row) => resolveIsfahanCityId(row) != null);
    const cityId = isfahan ? resolveIsfahanCityId(isfahan) : null;
    if (cityId == null) {
      process.stderr.write("[divar-neighborhood-sync] City catalog diagnostics: " +
        JSON.stringify({ keys: Object.keys(cityPayload ?? {}), sample: cityRows.slice(0, 12) }) + "\\n");
      throw new Error("Could not resolve Isfahan's current Divar city id from the city list");
    }

    const endpoint = "https://api.divar.ir/v8/places/cities/" + cityId + "/districts";
    const payload = await fetchJson(endpoint);
    const rows = listRows(payload, ["districts", "places", "items"]);
    if (!Array.isArray(rows) || rows.length < 25) {
      throw new Error("Divar returned an empty or incomplete Isfahan neighborhood catalog");
    }
    const districts = rows.map(normalizeDistrict).filter(Boolean);
    const coordinateCount = districts.filter((district) => district.default_location || district.bbox).length;
    if (districts.length < 25 || coordinateCount < 20) {
      const sample = rows.slice(0, 5).map((row) => ({
        keys: row && typeof row === "object" ? Object.keys(row) : [],
        id: row?.id,
        name: row?.name,
        default_location: row?.default_location ?? row?.defaultLocation ?? row?.center ?? row?.location,
        centroid: row?.centroid ?? row?.center_point,
        bbox: row?.bbox,
      }));
      process.stderr.write("[divar-neighborhood-sync] Catalog diagnostics: " +
        JSON.stringify({ rowCount: rows.length, normalizedCount: districts.length, coordinateCount, sample }) + "\\n");
      throw new Error("Divar catalog did not contain enough usable neighborhood locations");
    }

    const catalog = {
      cityId,
      source: "Divar",
      syncedAt: new Date().toISOString(),
      districts,
    };
    await writeFile(
      target,
      header + "export const DIVAR_ISFAHAN_CATALOG: DivarIsfahanCatalog = " +
        JSON.stringify(catalog, null, 2) + ";\n",
      "utf8",
    );
    process.stdout.write(
      "[divar-neighborhood-sync] Synced " + districts.length +
      " Isfahan districts (" + coordinateCount + " with map geometry/points).\n",
    );
  } catch (error) {
    let cached = false;
    try {
      const current = await readFile(target, "utf8");
      cached = current.includes('"source": "Divar"') &&
        (current.match(/"name":/g) ?? []).length > 25;
    } catch {
      // A first build may have only the checked-in fallback catalog.
    }
    process.stderr.write(
      "[divar-neighborhood-sync] Could not refresh the catalog: " +
      String(error?.message ?? error) + ". " +
      (cached ? "Using the last cached Divar catalog.\n" : "Using the checked-in fallback locations.\n"),
    );
  }
}

await main();
