-- Central, canonical neighborhood catalog for Hirmand.
-- This migration does not fabricate coordinates; Google Maps resolves the
-- neighborhood destination from its canonical Persian name.
create table if not exists neighborhoods (
  name text primary key,
  group_title text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists neighborhoods_active_group_idx
  on neighborhoods (is_active, group_title, name);

-- Keep every neighborhood already present on a property, even when an older
-- admin entry used a value that was not in the canonical catalog.
insert into neighborhoods (name, group_title)
select distinct trim(p.neighborhood), 'سایر'
from properties p
where trim(coalesce(p.neighborhood, '')) <> ''
on conflict (name) do nothing;

